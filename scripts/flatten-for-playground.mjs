// Builds anchor/playground/lib.rs: lib.rs + rules.rs inlined into ONE file for Solana Playground.
//   node scripts/flatten-for-playground.mjs
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const src = path.resolve(import.meta.dirname, "../anchor/programs/medtrace/src");
const lib = readFileSync(path.join(src, "lib.rs"), "utf8");
const rules = readFileSync(path.join(src, "rules.rs"), "utf8")
  .replace(/\n#\[cfg\(test\)\]\nmod tests \{[\s\S]*\}\s*$/, "\n") // unit tests run via rules-tests/, not on-chain
  .replace(/^\/\/!/gm, "//");

if (!lib.includes("pub mod rules;")) throw new Error("lib.rs no longer declares `pub mod rules;`");
const indented = rules.trimEnd().split("\n").map((l) => (l ? "    " + l : l)).join("\n");
const flat =
  "// GENERATED by scripts/flatten-for-playground.mjs. Edit anchor/programs/medtrace/src/*.rs instead.\n" +
  "// Paste this whole file into Solana Playground → src/lib.rs → Build → Deploy.\n\n" +
  lib.replace("pub mod rules;", `pub mod rules {\n${indented}\n}`);

const out = path.resolve(import.meta.dirname, "../anchor/playground/lib.rs");
writeFileSync(out, flat);
console.log(`wrote ${out} (${flat.split("\n").length} lines)`);
